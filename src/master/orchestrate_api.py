# ── Common workspace/topic validation ────────────────────────────────────────

def _assert_workspace_and_topic(conn, workspace_id: str, topic_id: str) -> None:
    if conn.execute(
        "SELECT id FROM workspaces WHERE id = ? AND archived_at IS NULL",
        (workspace_id,),
    ).fetchone() is None:
        raise HTTPException(404, "workspace not found")
    if conn.execute(
        "SELECT id FROM topics WHERE id = ? AND workspace_id = ? AND archived_at IS NULL",
        (topic_id, workspace_id),
    ).fetchone() is None:
        raise HTTPException(404, "topic not found")


# ── delegate_task ──────────────────────────────────────────────────────────────

@router.post("/delegate", response_model=DelegateOut, status_code=200)
async def delegate_task(
    workspace_id: str,
    topic_id: str,
    body: DelegateIn,
    request: Request,
) -> DelegateOut:
    app_state = request.app.state
    db_path = app_state.db_path

    conn = get_connection(db_path)
    try:
        _assert_workspace_and_topic(conn, workspace_id, topic_id)
        _verify_caller_identity(conn, body.caller_message_id, body.caller_staff, topic_id)
        _verify_dispatch_token(conn, body.caller_message_id, body.dispatch_token, topic_id)

        if body.caller_staff == body.staff:
            LOGGER.warning(
                "orchestration.guard_hit guard=self_delegation task_id=None topic_id=%s",
                topic_id,
            )
            raise HTTPException(422, "self_delegation")

        target_staff = resolve_staff(conn, body.staff, workspace_id, topic_id)
        if target_staff is None:
            LOGGER.warning(
                "orchestration.guard_hit guard=unknown_staff task_id=None topic_id=%s",
                topic_id,
            )
            raise HTTPException(404, "staff not found")

        effective_max_depth = get_effective_max_delegation_depth(conn, workspace_id)
        effective_max_root = get_effective_max_tasks_per_root(conn, workspace_id)

        caller_task_row = None
        caller_depth = 0
        prompt_row = conn.execute(
            "SELECT task_id FROM messages WHERE id = ?", (body.caller_message_id,)
        ).fetchone()
        if prompt_row and prompt_row["task_id"]:
            caller_task_row = conn.execute(
                "SELECT * FROM tasks WHERE id = ?", (prompt_row["task_id"],)
            ).fetchone()
            if caller_task_row:
                caller_depth = caller_task_row["depth"]

        if caller_depth >= effective_max_depth:
            LOGGER.warning(
                "orchestration.guard_hit guard=depth_exceeded task_id=%s topic_id=%s",
                caller_task_row["id"] if caller_task_row else None,
                topic_id,
            )
            raise HTTPException(422, "depth_exceeded")

        new_depth = caller_depth + 1

        root_task_id: str | None = None
        parent_task_id: str | None = None
        dispatcher_kind = "staff"
        dispatcher_name = body.caller_staff

        if caller_task_row:
            root_task_id = caller_task_row["root_task_id"]
            parent_task_id = caller_task_row["id"]
            count = conn.execute(
                "SELECT COUNT(*) FROM tasks WHERE root_task_id = ?", (root_task_id,)
            ).fetchone()[0]
            if count >= effective_max_root:
                LOGGER.warning(
                    "orchestration.guard_hit guard=fan_out_exceeded task_id=%s topic_id=%s",
                    caller_task_row["id"],
                    topic_id,
                )
                raise HTTPException(422, "fan_out_exceeded")

        if caller_task_row:
            ancestors = []
            ancestor_id: str | None = caller_task_row["parent_task_id"]
            while ancestor_id:
                row = conn.execute(
                    "SELECT assignee_name, dispatcher_name, parent_task_id FROM tasks WHERE id = ?",
                    (ancestor_id,),
                ).fetchone()
                if row is None:
                    break
                ancestors.append(row)
                ancestor_id = row["parent_task_id"]
            if detect_cycle(ancestors, body.staff):
                LOGGER.warning(
                    "orchestration.guard_hit guard=cycle_detected task_id=%s topic_id=%s",
                    caller_task_row["id"],
                    topic_id,
                )
                raise HTTPException(422, "cycle_detected")

        try:
            validate_envelope(
                sender_kind="staff",
                sender_name=body.caller_staff,
                receiver_kind="staff",
                receiver_name=body.staff,
                task_id="pending",
            )
        except ValueError as exc:
            LOGGER.warning(
                "orchestration.guard_hit guard=%s task_id=%s topic_id=%s",
                str(exc),
                caller_task_row["id"] if caller_task_row else None,
                topic_id,
            )
            raise HTTPException(422, str(exc)) from exc

        task_id = str(uuid.uuid4())
        if root_task_id is None:
            root_task_id = task_id
        now = _now()

        conn.execute(
            "INSERT INTO tasks"
            " (id, topic_id, root_task_id, parent_task_id, depth,"
            "  dispatcher_kind, dispatcher_name, assignee_name,"
            "  goal, acceptance_criteria, state, failure_score,"
            "  created_at, updated_at)"
            " VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, 'submitted', 0.0, ?, ?)",
            (
                task_id, topic_id, root_task_id, parent_task_id, new_depth,
                dispatcher_kind, dispatcher_name, body.staff,
                body.goal, body.acceptance_criteria, now, now,
            ),
        )
        conn.commit()
    finally:
        conn.close()

    topic_lock = get_topic_lock(topic_id)
    acquired = topic_lock.acquire(blocking=False)
    if not acquired:
        # Another task is in-flight on this topic — queue this one.
        # queued_position is advisory/approximate: it is counted after insertion and
        # may not match the final dispatch order if concurrent delegates race.
        queued_position = _count_queued_tasks(db_path, topic_id)
        LOGGER.info(
            "orchestration.task_queued task_id=%s topic_id=%s position=%d",
            task_id, topic_id, queued_position,
        )
        return DelegateOut(task_id=task_id, state="queued", queued_position=queued_position)

    # Lock acquired — dispatch the assignee's first prompt immediately.
    try:
        await _dispatch_task_first_prompt(
            app_state=app_state,
            workspace_id=workspace_id,
            topic_id=topic_id,
            task_id=task_id,
            target_staff=target_staff,
            body=body,
            db_path=db_path,
        )
    except Exception:
        topic_lock.release()
        raise

    return DelegateOut(task_id=task_id, state="working")


def _count_queued_tasks(db_path: str, topic_id: str) -> int:
    conn = get_connection(db_path)
    try:
        return conn.execute(
            "SELECT COUNT(*) FROM tasks WHERE topic_id = ? AND state = 'submitted'",
            (topic_id,),
        ).fetchone()[0]
    finally:
        conn.close()


async def _dispatch_task_first_prompt(
    *,
    app_state,
    workspace_id: str,
    topic_id: str,
    task_id: str,
    target_staff,
    body: DelegateIn,
    db_path: str,
) -> None:
    """Dispatch the assignee's first prompt and transition task to 'working'."""
    prompt_text = _build_prompt(body.goal, body.acceptance_criteria, body.context)

    from .dispatch import dispatch_to_staff
    await dispatch_to_staff(
        app_state=app_state,
        workspace_id=workspace_id,
        topic_id=topic_id,
        staff=target_staff,
        prompt_text=prompt_text,
        sender="event",
        sender_kind="staff",
        sender_name=body.caller_staff,
        receiver_kind="staff",
        receiver_name=body.staff,
        task_id=task_id,
        reply_to_message_id=body.caller_message_id,
    )

    state_conn = get_connection(db_path)
    try:
        state_conn.execute(
            "UPDATE tasks SET state = 'working', updated_at = ? WHERE id = ?",
            (_now(), task_id),
        )
        state_conn.commit()
    finally:
        state_conn.close()


# ── ask_sender ────────────────────────────────────────────────────────────────

@router.post("/ask", response_model=AskOut, status_code=200)
async def ask_sender(
    workspace_id: str,
    topic_id: str,
    body: AskIn,
    request: Request,
) -> AskOut:
    app_state = request.app.state
    db_path = app_state.db_path

    conn = get_connection(db_path)
    try:
        _assert_workspace_and_topic(conn, workspace_id, topic_id)
        _verify_caller_identity(conn, body.caller_message_id, body.caller_staff, topic_id)
        _verify_dispatch_token(conn, body.caller_message_id, body.dispatch_token, topic_id)

        prompt_row = conn.execute(
            "SELECT task_id FROM messages WHERE id = ?", (body.caller_message_id,)
        ).fetchone()

        task_row = None
        if prompt_row and prompt_row["task_id"]:
            task_row = conn.execute(
                "SELECT * FROM tasks WHERE id = ?", (prompt_row["task_id"],)
            ).fetchone()

        task_state = "n/a"
        receiver_kind = "user"
        receiver_name = None

        if task_row:
            caller_is_dispatcher = (body.caller_staff == task_row["dispatcher_name"])

            if caller_is_dispatcher:
                # The dispatcher is asking — route UP to whoever dispatched the dispatcher.
                # For v1 depth-1 tasks the dispatcher has no parent task, so its sender is
                # always the user.  For deeper trees we look up the parent task's dispatcher.
                parent_task_id = task_row["parent_task_id"]
                if parent_task_id:
                    parent_task = conn.execute(
                        "SELECT dispatcher_kind, dispatcher_name FROM tasks WHERE id = ?",
                        (parent_task_id,),
                    ).fetchone()
                    if parent_task:
                        receiver_kind = parent_task["dispatcher_kind"]
                        receiver_name = parent_task["dispatcher_name"]
                    else:
                        receiver_kind = "user"
                        receiver_name = None
                else:
                    receiver_kind = "user"
                    receiver_name = None
            else:
                # Caller is the assignee — ask the task's dispatcher.
                receiver_kind = task_row["dispatcher_kind"]
                receiver_name = task_row["dispatcher_name"]

            # Safety guard: never allow a question whose receiver equals the caller.
            # If the routing above still resolves to the caller itself, escalate to user.
            if receiver_name == body.caller_staff:
                LOGGER.warning(
                    "orchestration.guard_hit guard=self_question_prevented task_id=%s"
                    " topic_id=%s caller=%s computed_receiver=%s — routing to user",
                    task_row["id"], topic_id, body.caller_staff, receiver_name,
                )
                receiver_kind = "user"
                receiver_name = None

            try:
                apply_transition(task_row["state"], "ask_sender")
            except IllegalTransition:
                LOGGER.warning(
                    "orchestration.guard_hit guard=illegal_transition task_id=%s"
                    " topic_id=%s current_state=%s event=ask_sender",
                    task_row["id"], topic_id, task_row["state"],
                )
                raise HTTPException(409, "illegal_transition")
            task_state = "input-required"

        # Generate the question message UUID and insert the row immediately for all receiver kinds.
        # This makes the message visible in the DB as soon as ask_sender returns, regardless of
        # whether the receiver is a user or a staff member.
        # For staff receivers: a staged dispatch is also queued so process_turn_end fires MQTT
        # at turn-end (dispatch_to_staff is called with insert_row=False to skip re-inserting).
        # sender='agent' for user-receiver questions (visible chat bubble);
        # sender='event' for staff-receiver questions (matches dispatch_to_staff convention).
        message_id = str(uuid.uuid4())
        dispatch_token_for_question = str(uuid.uuid4())
        question_sender = "agent" if receiver_kind == "user" else "event"

        conn.execute(
            "INSERT INTO messages"
            " (id, topic_id, sender, agent_name, text, transcript, usage_json, attachments_json,"
            "  silent, created_at,"
            "  sender_kind, sender_name, receiver_kind, receiver_name,"
            "  task_id, reply_to_message_id, dispatch_token)"
            " VALUES (?, ?, ?, ?, ?, NULL, NULL, NULL, 0, ?,"
            "         'staff', ?, ?, ?, ?, ?, ?)",
            (
                message_id, topic_id, question_sender, body.caller_staff, body.question, _now(),
                body.caller_staff, receiver_kind, receiver_name,
                task_row["id"] if task_row else None,
                body.caller_message_id,
                dispatch_token_for_question,
            ),
        )

        if task_row:
            conn.execute(
                "UPDATE tasks SET state = 'input-required', updated_at = ? WHERE id = ?",
                (_now(), task_row["id"]),
            )
            # For staff receivers: stage the question dispatch so process_turn_end publishes
            # MQTT when the caller's turn ends. The message row is already written above;
            # dispatch_to_staff will be called with insert_row=False to avoid a duplicate.
            if receiver_kind == "staff":
                _stage_dispatch(
                    conn,
                    prompt_message_id=body.caller_message_id,
                    topic_id=topic_id,
                    sender_name=body.caller_staff,
                    receiver_kind=receiver_kind,
                    receiver_name=receiver_name,
                    task_id=task_row["id"],
                    kind="question",
                    body=json.dumps({
                        "message_id": message_id,
                        "text": body.question,
                    }),
                )
        conn.commit()
    finally:
        conn.close()

    # Broadcast the question for user-receiver questions so the UI shows the bubble immediately.
    # For staff-receiver questions the broadcast happens when the staged dispatch fires
    # (inside dispatch_to_staff at turn-end).
    if receiver_kind == "user":
        await app_state.hub.broadcast("_global", {
            "type": "message",
            "topic_id": topic_id,
            "message_id": message_id,
            "sender": "agent",
            "agent_name": body.caller_staff,
            "text": body.question,
            "transcript": None,
            "attachments": [],
            "sender_kind": "staff",
            "sender_name": body.caller_staff,
            "receiver_kind": receiver_kind,
            "receiver_name": receiver_name,
            "task_id": task_row["id"] if task_row else None,
            "reply_to_message_id": body.caller_message_id,
        })

    return AskOut(message_id=message_id, task_state=task_state)


# ── submit_result ─────────────────────────────────────────────────────────────

@router.post("/submit_result", response_model=SubmitResultOut, status_code=200)
async def submit_result(
    workspace_id: str,
    topic_id: str,
    body: SubmitResultIn,
    request: Request,
) -> SubmitResultOut:
    db_path = request.app.state.db_path

    if body.status not in ("completed", "failed"):
        raise HTTPException(422, "invalid_status")

    conn = get_connection(db_path)
    try:
        _assert_workspace_and_topic(conn, workspace_id, topic_id)
        _verify_caller_identity(conn, body.caller_message_id, body.caller_staff, topic_id)
        _verify_dispatch_token(conn, body.caller_message_id, body.dispatch_token, topic_id)

        prompt_row = conn.execute(
            "SELECT task_id FROM messages WHERE id = ?", (body.caller_message_id,)
        ).fetchone()
        if not prompt_row or not prompt_row["task_id"]:
            LOGGER.warning(
                "orchestration.guard_hit guard=no_task_context task_id=None topic_id=%s"
                " endpoint=submit_result",
                topic_id,
            )
            raise HTTPException(422, "no_task_context")

        task_row = conn.execute(
            "SELECT * FROM tasks WHERE id = ?", (prompt_row["task_id"],)
        ).fetchone()
        if task_row is None:
            raise HTTPException(404, "task not found")

        if task_row["assignee_name"] != body.caller_staff:
            LOGGER.warning(
                "orchestration.guard_hit guard=not_assignee task_id=%s topic_id=%s",
                task_row["id"], topic_id,
            )
            raise HTTPException(403, "not_assignee")

        try:
            apply_transition(task_row["state"], "submit_result")
        except IllegalTransition:
            LOGGER.warning(
                "orchestration.guard_hit guard=illegal_transition task_id=%s topic_id=%s"
                " current_state=%s event=submit_result",
                task_row["id"], topic_id, task_row["state"],
            )
            raise HTTPException(409, "illegal_transition")

        artifacts_json = json.dumps(body.artifacts or [])

        # Remove any prior staged result for this prompt to implement last-call-wins.
        conn.execute(
            "DELETE FROM staged_dispatches"
            " WHERE prompt_message_id = ? AND kind = 'result_ready'",
            (body.caller_message_id,),
        )

        conn.execute(
            "UPDATE tasks SET result_summary = ?, result_artifacts = ?, result_status = ?,"
            " updated_at = ? WHERE id = ?",
            (body.summary, artifacts_json, body.status, _now(), task_row["id"]),
        )
        _stage_dispatch(
            conn,
            prompt_message_id=body.caller_message_id,
            topic_id=topic_id,
            sender_name=body.caller_staff,
            receiver_kind=task_row["dispatcher_kind"],
            receiver_name=task_row["dispatcher_name"],
            task_id=task_row["id"],
            kind="result_ready",
            body=json.dumps({
                "summary": body.summary,
                "status": body.status,
                "artifacts": body.artifacts or [],
            }),
        )
        conn.commit()
    finally:
        conn.close()

    return SubmitResultOut(task_id=prompt_row["task_id"], state="working")


