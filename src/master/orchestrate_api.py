async def _dispatch_free_text_to_staff(
    *,
    app_state,
    workspace_id: str,
    topic_id: str,
    agent_name: str,
    reply_text: str,
    task_row,
    prompt_message_id: str,
    reply_message_id: str,
    receiver_name: str,
) -> None:
    """Dispatch the free-text reply to the staff dispatcher (phase-a-style plain reply inside task)."""
    db_path = app_state.db_path
    target_staff = _resolve_staff_for_topic(db_path, workspace_id, topic_id, receiver_name)
    if target_staff is None:
        LOGGER.warning(
            "orchestration.dispatch_failed reason=staff_not_found name=%s task_id=%s",
            receiver_name, task_row["id"] if task_row else None,
        )
        return

    from .dispatch import dispatch_to_staff
    await dispatch_to_staff(
        app_state=app_state,
        workspace_id=workspace_id,
        topic_id=topic_id,
        staff=target_staff,
        prompt_text=reply_text,
        sender="event",
        sender_kind="staff",
        sender_name=agent_name,
        receiver_kind="staff",
        receiver_name=receiver_name,
        task_id=task_row["id"] if task_row else None,
        reply_to_message_id=reply_message_id,
    )


def _resolve_staff_for_topic(db_path: str, workspace_id: str, topic_id: str, name: str):
    conn = get_connection(db_path)
    try:
        return resolve_staff(conn, name, workspace_id, topic_id)
    finally:
        conn.close()


# ── Next-queued dispatch ──────────────────────────────────────────────────────

async def _dispatch_next_queued(app_state, workspace_id: str, topic_id: str) -> None:
    """Dispatch the oldest submitted (queued) task for a topic, if any.

    Called after the current in-flight task completes and the lock has been
    released.  Serialised by the per-topic threading.Lock: we try to acquire
    it; if another coroutine already grabbed it, they will handle the queue.
    """
    db_path = app_state.db_path
    topic_lock = get_topic_lock(topic_id)
    acquired = topic_lock.acquire(blocking=False)
    if not acquired:
        return  # another dispatch already in progress

    try:
        conn = get_connection(db_path)
        try:
            # SELECT and UPDATE in one connection/transaction to avoid TOCTOU between
            # the existence check and the state stamp (M-6).
            task_row = conn.execute(
                "SELECT * FROM tasks WHERE topic_id = ? AND state = 'submitted'"
                " ORDER BY created_at LIMIT 1",
                (topic_id,),
            ).fetchone()
            if task_row is None:
                # No queued task — release the lock before returning (C-1).
                topic_lock.release()
                return

            ws_row = conn.execute(
                "SELECT id FROM workspaces WHERE id = ("
                " SELECT workspace_id FROM topics WHERE id = ?)",
                (topic_id,),
            ).fetchone()
            ws_id = ws_row["id"] if ws_row else workspace_id

            target_staff = resolve_staff(conn, task_row["assignee_name"], ws_id, topic_id)
            staff_found = target_staff is not None

            if staff_found:
                conn.execute(
                    "UPDATE tasks SET state = 'working', updated_at = ? WHERE id = ?",
                    (_now(), task_row["id"]),
                )
                conn.commit()
        finally:
            conn.close()

        if not staff_found:
            LOGGER.warning(
                "orchestration.dispatch_failed reason=staff_not_found name=%s task_id=%s",
                task_row["assignee_name"], task_row["id"],
            )
            topic_lock.release()
            return

        # Queued tasks have never been dispatched, so no prompt message exists yet.
        # Reconstruct the prompt from the task's goal and acceptance_criteria columns,
        # mirroring _dispatch_task_first_prompt.
        prompt_text = _build_prompt(
            task_row["goal"],
            task_row["acceptance_criteria"] or "",
            None,
        )

        from .dispatch import dispatch_to_staff
        await dispatch_to_staff(
            app_state=app_state,
            workspace_id=ws_id,
            topic_id=topic_id,
            staff=target_staff,
            prompt_text=prompt_text,
            sender="event",
            sender_kind="staff",
            sender_name=task_row["dispatcher_name"] or "",
            receiver_kind="staff",
            receiver_name=task_row["assignee_name"],
            task_id=task_row["id"],
            reply_to_message_id=None,
        )
        LOGGER.info(
            "orchestration.queued_task_dispatched task_id=%s topic_id=%s",
            task_row["id"], topic_id,
        )
    except Exception:
        LOGGER.exception("orchestration.dispatch_next_queued_error topic_id=%s", topic_id)
        try:
            topic_lock.release()
        except RuntimeError:
            pass


# ── Startup scan ──────────────────────────────────────────────────────────────

def dispatch_undispatched_staged_rows(app_state, loop: asyncio.AbstractEventLoop) -> None:
    """Dispatch any staged rows whose turn's /response was saved before a master restart.

    Called once at startup from the lifespan context.  For each undispatched
    staged row, we check whether the prompt's /response message already exists;
    if yes, the turn completed but the dispatch was interrupted, so we re-dispatch
    it now.  If the response does not exist, redelivery of the MQTT prompt will
    handle it naturally.
    """
    db_path = app_state.db_path
    conn = get_connection(db_path)
    try:
        rows = conn.execute(
            "SELECT sd.*, m.topic_id AS prompt_topic_id"
            " FROM staged_dispatches sd"
            " JOIN messages m ON m.id = sd.prompt_message_id"
            " WHERE sd.dispatched_at IS NULL",
        ).fetchall()
        # For each undispatched row, find the agent response that already closed the turn
        # so we can pass the correct reply_message_id (M-1: preserves reply chain).
        orphaned: list[tuple] = []
        for r in rows:
            response_row = conn.execute(
                "SELECT id FROM messages WHERE reply_to_message_id = ? AND sender = 'agent'"
                " ORDER BY created_at DESC LIMIT 1",
                (r["prompt_message_id"],),
            ).fetchone()
            if response_row:
                orphaned.append((r, response_row["id"]))
    finally:
        conn.close()

    if not orphaned:
        return

    LOGGER.info("orchestration.startup_scan orphaned_staged=%d", len(orphaned))
    for staged, reply_message_id in orphaned:
        topic_id = staged["topic_id"]

        # M-2: skip topics whose lock is held — an in-flight turn will advance them.
        topic_lock = get_topic_lock(topic_id)
        if not topic_lock.acquire(blocking=False):
            LOGGER.info(
                "orchestration.startup_scan skipped_locked topic_id=%s staged_id=%s",
                topic_id, staged["id"],
            )
            continue

        ws_conn = get_connection(db_path)
        try:
            ws_row = ws_conn.execute(
                "SELECT workspace_id FROM topics WHERE id = ?", (topic_id,)
            ).fetchone()
            workspace_id = ws_row["workspace_id"] if ws_row else ""
        finally:
            ws_conn.close()

        asyncio.run_coroutine_threadsafe(
            _startup_execute_and_release(
                app_state=app_state,
                workspace_id=workspace_id,
                topic_id=topic_id,
                staged=staged,
                reply_message_id=reply_message_id,
                db_path=db_path,
                topic_lock=topic_lock,
            ),
            loop,
        )


async def _startup_execute_and_release(
    *,
    app_state,
    workspace_id: str,
    topic_id: str,
    staged,
    reply_message_id: str,
    db_path: str,
    topic_lock: threading.Lock,
) -> None:
    """Execute a single orphaned staged row and release the topic lock (M-2, C-3)."""
    try:
        await _execute_staged_row(
            app_state=app_state,
            workspace_id=workspace_id,
            topic_id=topic_id,
            staged=staged,
            reply_message_id=reply_message_id,
            db_path=db_path,
        )
    finally:
        try:
            topic_lock.release()
        except RuntimeError:
            pass
