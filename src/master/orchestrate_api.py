def _now() -> str:
    return datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


# ── Caller identity + token verification ──────────────────────────────────────

def _verify_caller_identity(
    conn,
    caller_message_id: str,
    caller_staff: str,
    topic_id: str,
) -> None:
    """Bind the caller's claimed identity to a genuinely dispatched prompt row.

    Phase-b binding: the caller_message_id row must (a) exist, (b) belong to
    this topic, and (c) when the row carries identity fields, at least one must
    match caller_staff.  Token verification happens separately via
    _verify_dispatch_token when a dispatch_token is present in the request.

    Rows without identity fields (legacy user messages, synthetic test rows
    without receiver_name/agent_name) bypass the name-match and are accepted.
    """
    row = conn.execute(
        "SELECT topic_id, receiver_name, agent_name FROM messages WHERE id = ?",
        (caller_message_id,),
    ).fetchone()
    if row is None:
        LOGGER.warning(
            "orchestration.guard_hit guard=caller_mismatch task_id=None topic_id=%s"
            " reason=unknown_message_id",
            topic_id,
        )
        raise HTTPException(422, "caller_mismatch")
    if row["topic_id"] != topic_id:
        LOGGER.warning(
            "orchestration.guard_hit guard=caller_mismatch task_id=None topic_id=%s"
            " reason=wrong_topic",
            topic_id,
        )
        raise HTTPException(422, "caller_mismatch")
    receiver_name = row["receiver_name"]
    agent_name = row["agent_name"]
    if (receiver_name is not None or agent_name is not None) and caller_staff not in (
        receiver_name,
        agent_name,
    ):
        LOGGER.warning(
            "orchestration.guard_hit guard=caller_mismatch task_id=None topic_id=%s"
            " reason=name_mismatch caller=%s",
            topic_id,
            caller_staff,
        )
        raise HTTPException(422, "caller_mismatch")


def _verify_dispatch_token(
    conn,
    caller_message_id: str,
    dispatch_token: str,
    topic_id: str,
) -> None:
    """Verify that the dispatch_token matches the token stored on the prompt row.

    The token is a per-dispatch UUID generated by dispatch_to_staff and stored
    in messages.dispatch_token.  A mismatch indicates a forged or replayed call.
    """
    row = conn.execute(
        "SELECT dispatch_token FROM messages WHERE id = ?",
        (caller_message_id,),
    ).fetchone()
    if row is None or row["dispatch_token"] != dispatch_token:
        LOGGER.warning(
            "orchestration.guard_hit guard=invalid_dispatch_token topic_id=%s"
            " caller_message_id=%s",
            topic_id,
            caller_message_id,
        )
        raise HTTPException(403, "invalid_dispatch_token")


# ── Helper: workspace lookup for a topic ────────────────────────────────────

def _get_workspace_id(conn, topic_id: str) -> str | None:
    row = conn.execute("SELECT workspace_id FROM topics WHERE id = ?", (topic_id,)).fetchone()
    return row["workspace_id"] if row else None


# ── Staged dispatch helpers ──────────────────────────────────────────────────

def _stage_dispatch(
    conn,
    prompt_message_id: str,
    topic_id: str,
    sender_name: str,
    receiver_kind: str,
    receiver_name: str | None,
    task_id: str,
    kind: str,
    body: str,
) -> str:
    """Insert a staged_dispatches row and return its id."""
    row_id = str(uuid.uuid4())
    conn.execute(
        "INSERT INTO staged_dispatches"
        " (id, prompt_message_id, topic_id, sender_name, receiver_kind, receiver_name,"
        "  task_id, kind, body, created_at)"
        " VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?)",
        (
            row_id, prompt_message_id, topic_id, sender_name, receiver_kind, receiver_name,
            task_id, kind, body, _now(),
        ),
    )
    return row_id


def _stamp_dispatched(conn, row_id: str) -> None:
    conn.execute(
        "UPDATE staged_dispatches SET dispatched_at = ? WHERE id = ?",
        (_now(), row_id),
    )


# ── Prompt-text builder ──────────────────────────────────────────────────────

_ASSIGNEE_INSTRUCTION_FOOTER = (
    "\n\n---\n"
    "You are the assignee of the task above. Use the `ask_sender` tool "
    "for any clarifying questions — do not ask in plain text. "
    "When finished, submit your result via `submit_result(status, summary, artifacts)`. "
    "Your plain reply text is not delivered as a question and will not reach anyone."
)

_ANSWER_DELIVERY_FOOTER = (
    "\n\n---\n"
    "The answer above was provided by your dispatcher. "
    "Continue working on the task and finish with `submit_result(status, summary, artifacts)`."
)


def _build_prompt(goal: str, acceptance_criteria: str, context: str | None) -> str:
    parts = []
    if context:
        parts.append(f"**Context:**\n{context}")
    parts.append(f"**Goal:**\n{goal}")
    parts.append(f"**Acceptance criteria:**\n{acceptance_criteria}")
    return "\n\n".join(parts) + _ASSIGNEE_INSTRUCTION_FOOTER


def _build_judgment_prompt(task: object, result_summary: str, result_status: str) -> str:
    goal = task["goal"]  # type: ignore[index]
    criteria = task["acceptance_criteria"] or ""
    return (
        f"Task (id={task['id']!r}, goal={goal!r}) completed by @{task['assignee_name']}.\n\n"  # type: ignore[index]
        f"**Result status:** {result_status}\n\n"
        f"**Result summary:**\n{result_summary}\n\n"
        f"**Acceptance criteria:**\n{criteria}\n\n"
        "Please call `accept_result` if the result meets the criteria.  "
        "In phase (b) rejection and give-up are not yet available — "
        "if you need changes, provide feedback as free text (it will be recorded) "
        "and the task will remain in its current state pending further action."
    )


