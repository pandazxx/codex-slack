"""Internal REST endpoints for the orchestration MCP server.

Called by the in-container orchestrate MCP process over HTTP; not part of the
public API surface. Endpoints per topic:

  POST .../orchestrate/delegate      — create a task, queue or dispatch the assignee's first prompt
  POST .../orchestrate/ask           — stage a clarifying question to the dispatcher or user
  POST .../orchestrate/submit_result — stage a result envelope from the assignee
  POST .../orchestrate/answer_question — stage an answer from the dispatcher to the assignee
  POST .../orchestrate/accept_result — accept the assignee's result, close the task
  GET  .../orchestrate/tasks         — list task rows for the UI

Turn re-entry (phase b):

  process_turn_end() is called from the MQTT /response handler after
  _save_agent_response completes.  It dispatches all staged rows for the
  completed prompt_message_id, then routes the free-text response per §7.

Startup scan:

  dispatch_undispatched_staged_rows() is called at startup to re-dispatch any
  staged rows whose turn's /response was already saved but the dispatch was
  interrupted by a master restart.
"""
