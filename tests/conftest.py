# ---------------------------------------------------------------------------
# Route coverage tracking (guard 4b)
#
# Enabled when ENFORCE_ROUTE_COVERAGE=1 (set by .sre/test-db.sh on the
# non-SQLite legs).  A starlette HTTP middleware records the route template
# for every request that hits the FastAPI app.  A session-end fixture fails
# the suite if any non-allowlisted route was never hit.
#
# The fixture is no-op when ENFORCE_ROUTE_COVERAGE is not set, so running a
# single test locally is never broken by this.
# ---------------------------------------------------------------------------

# Routes that are intentionally excluded from the coverage requirement.
_ROUTE_COVERAGE_ALLOWLIST: frozenset[tuple[str, str]] = frozenset({
    # WebSocket — can't be hit via TestClient HTTP requests.
    ("WS", "/ws/events"),
    # SPA fallback — hits on any unknown path; existence is tested separately.
    ("GET", "/{full_path:path}"),
    # OpenAPI schema / docs auto-generated by FastAPI.
    ("GET", "/openapi.json"),
    ("HEAD", "/openapi.json"),
    ("GET", "/docs"),
    ("HEAD", "/docs"),
    ("GET", "/docs/oauth2-redirect"),
    ("HEAD", "/docs/oauth2-redirect"),
    ("GET", "/redoc"),
    ("HEAD", "/redoc"),
    # Health check — covered by test_health.py but not safety-net-critical.
    ("GET", "/health"),
    # Schema introspection endpoint — covered by test_main.py.
    ("GET", "/schema"),
})

_ROUTE_COVERAGE_ENABLED: bool = (
    os.environ.get("ENFORCE_ROUTE_COVERAGE", "0").strip() in ("1", "true", "yes")
)
_routes_hit: set[tuple[str, str]] = set()


def _collect_routes(router, prefix: str = "") -> list[tuple[set[str] | None, str]]:
    """Walk a FastAPI/Starlette router recursively and return (methods, path) pairs.

    In FastAPI 0.160+, routes added via include_router() are stored as
    _IncludedRouter objects.  The include_context holds the prefix passed to
    include_router() (e.g. "/api"), while the original_router's routes already
    carry any prefix the sub-router declared on its own routes (e.g. the config
    router already has "/config/system-variables" baked into its APIRoute.path).

    Crucially, scope["route"].path in an HTTP middleware is set to
    original_route.path — the path stored on the matched APIRoute object from
    the original sub-router — which does NOT include the include_context prefix.
    _collect_routes must therefore return those same paths so that the route
    tracker can compare them correctly.

    Mounted sub-apps and WebSocket routes are returned with methods=None so the
    caller can handle them separately.
    """
    results: list[tuple[set[str] | None, str]] = []
    for route in router.routes:
        typ = type(route).__name__
        path = getattr(route, "path", None)
        methods = getattr(route, "methods", None)

        if typ in ("APIRoute", "Route") and path is not None:
            results.append((methods, prefix + path))
        elif typ in ("APIWebSocketRoute", "WebSocketRoute") and path is not None:
            results.append((None, prefix + path))
        elif typ == "_IncludedRouter":
            # Do NOT add include_context.prefix here: scope["route"].path is
            # set to original_route.path, which already excludes that prefix.
            orig = getattr(route, "original_router", None)
            if orig is not None:
                results.extend(_collect_routes(orig, prefix))
        elif hasattr(route, "routes"):
            # Generic sub-router (Mount, etc.)
            sub_prefix = prefix + (path or "")
            results.extend(_collect_routes(route, sub_prefix))

    return results


# Module-level storage for routes missed this session.  Populated by
# _install_route_tracker teardown; consumed by pytest_sessionfinish.
_missing_routes: list[str] = []


@pytest.fixture(scope="session", autouse=True)
def _install_route_tracker():
    """Install an ASGI middleware that records which route templates are hit.

    Only active when ENFORCE_ROUTE_COVERAGE=1.  The middleware is added to the
    FastAPI app singleton before any TestClient is created, so every request
    during the session passes through it.

    At session teardown the fixture tallies uncovered routes and stores them in
    _missing_routes; pytest_sessionfinish then sets the exit code and prints a
    clear failure banner.  Failures from this guard never appear as an error on
    an unrelated test.
    """
    if not _ROUTE_COVERAGE_ENABLED:
        yield
        return

    print("\n[route-coverage] guard active — tracking route hits for this session")
    from src.master.main import app

    @app.middleware("http")
    async def _route_tracker(request, call_next):
        response = await call_next(request)
        # scope["route"] is set by Starlette's Router once a route is matched.
        route = request.scope.get("route")
        if route is not None and hasattr(route, "path"):
            methods = getattr(route, "methods", None) or set()
            for m in methods:
                _routes_hit.add((m, route.path))
        return response

    yield

    # Session teardown: tally coverage; do NOT raise here — raising attributes
    # the error to the last test that used this session fixture, which is always
    # an unrelated test.  pytest_sessionfinish handles the failure instead.
    all_app_routes = _collect_routes(app.router)
    required_pairs: list[tuple[str, str]] = []
    for methods, path in all_app_routes:
        if methods:
            for m in sorted(methods):
                required_pairs.append((m, path))
        else:
            required_pairs.append(("WS", path))

    for key in required_pairs:
        if key not in _ROUTE_COVERAGE_ALLOWLIST and key not in _routes_hit:
            _missing_routes.append(f"{key[0]} {key[1]}")

    _missing_routes.sort()
    non_allowlisted = sum(
        1 for k in required_pairs if k not in _ROUTE_COVERAGE_ALLOWLIST
    )
    print(
        f"\n[route-coverage] {len(_routes_hit)} request(s) recorded;"
        f" {non_allowlisted - len(_missing_routes)}/{non_allowlisted}"
        f" non-allowlisted routes hit"
    )


def pytest_sessionfinish(session, exitstatus):
    """After all tests, fail the session if any routes were never hit.

    This hook fires after _install_route_tracker teardown has populated
    _missing_routes.  By setting the exit status here we get a clear, named
    failure line instead of an error attributed to the last test in the run.
    """
    if not _ROUTE_COVERAGE_ENABLED or not _missing_routes:
        return
    lines = "\n  ".join(_missing_routes)
    msg = (
        f"\n[route-coverage] FAILED — {len(_missing_routes)} route(s) never hit"
        f" during the test session:\n  {lines}\n\n"
        "Add a test that exercises each missing route, or add it to\n"
        "_ROUTE_COVERAGE_ALLOWLIST in tests/conftest.py with a reason.\n"
    )
    print(msg, file=sys.stderr)
    session.exitstatus = 1


def pytest_configure(config):
    config.addinivalue_line(
        "markers",
        "sqlite_only: skip this test when DATABASE_URL points to a non-SQLite backend",
    )


@pytest.fixture(scope="session", autouse=True)
def _non_sqlite_schema_setup():
    """Run startup_db once per session so non-SQLite schemas exist before any test runs.

    On SQLite the per-test file URL already handles fresh-DB creation, so this
    fixture is a no-op for SQLite.  On Postgres/MySQL, DATABASE_URL is set in
    the outer environment by test-db.sh; the schema must exist before the first
    function-scoped truncation fixture fires.
    """
    url = os.environ.get("DATABASE_URL", "").strip() or os.environ.get("TEST_DATABASE_URL", "").strip()
    if not url or url.startswith("sqlite"):
        yield
        return
    from src.master.db import startup_db, _reset_engine_cache
    _reset_engine_cache()
    try:
        startup_db(url)
    except SystemExit as exc:
        pytest.exit(f"startup_db({url!r}) exited: {exc}", returncode=int(str(exc.code) or "1"))
    yield


@pytest.fixture(autouse=True)
def _skip_sqlite_only_on_non_sqlite(request):
    """Skip tests marked sqlite_only when DATABASE_URL points to a non-SQLite backend."""
    if request.node.get_closest_marker("sqlite_only") is None:
        yield
        return
    url = os.environ.get("DATABASE_URL", "").strip() or os.environ.get("TEST_DATABASE_URL", "").strip()
    if url and not url.startswith("sqlite"):
        pytest.skip(f"sqlite_only: skipped on {url.split('://')[0]} backend")
    yield


@pytest.fixture(autouse=True)
def _non_sqlite_truncate():
    """TRUNCATE all application tables before each test on non-SQLite backends.

    Rows from one test must not pollute the next test's unique-index checks.
    SQLite tests skip this — each gets its own per-test DB file via
    _set_test_database_url, so isolation is already guaranteed.
    """
    url = os.environ.get("DATABASE_URL", "").strip() or os.environ.get("TEST_DATABASE_URL", "").strip()
    if not url or url.startswith("sqlite"):
        yield
        return
    from src.master.db import TABLES, engine as db_engine
    from sqlalchemy import text as sa_text
    eng = db_engine(url)
    dialect = eng.dialect.name
    table_list = ", ".join(TABLES)
    with eng.connect() as conn:
        if dialect == "postgresql":
            conn.execute(sa_text("SET lock_timeout = '5s'"))
            conn.execute(sa_text(f"TRUNCATE TABLE {table_list} RESTART IDENTITY CASCADE"))
        elif dialect == "mysql":
            conn.execute(sa_text("SET FOREIGN_KEY_CHECKS = 0"))
            for table in TABLES:
                conn.execute(sa_text(f"TRUNCATE TABLE {table}"))
            conn.execute(sa_text("SET FOREIGN_KEY_CHECKS = 1"))
        conn.commit()
    yield


@pytest.fixture(autouse=True)
def _set_test_database_url(monkeypatch, tmp_path):
    """Set DATABASE_URL for each test so the app and db fixtures always have a URL.

    Resolution order (mirrors the production lifespan in src/master/main.py):

    1. If DATABASE_URL is already set in the environment (e.g. set before
       running pytest, as in CI against Postgres), leave it unchanged.
    2. If TEST_DATABASE_URL is set, use it as DATABASE_URL.  This lets the
       caller run the full suite against a specific backend without polluting
       the real DATABASE_URL variable.
    3. Otherwise, set DATABASE_URL to a per-test SQLite file inside tmp_path.
       This gives every test full isolation without requiring POSTGRES_PASSWORD
       or a live Postgres instance.

    Tests that need DATABASE_URL unset (e.g. tests/master/db/test_engine.py
    and test_regression.py that probe resolve_db_url/engine default behaviour)
    use monkeypatch.delenv("DATABASE_URL", raising=False) inside the test body,
    which takes effect for that test only and is restored automatically.
    """
    if "DATABASE_URL" in os.environ:
        yield
        return

    override = os.environ.get("TEST_DATABASE_URL", "")
    if override:
        monkeypatch.setenv("DATABASE_URL", override)
        yield
        return

    url = f"sqlite+pysqlite:///{tmp_path}/master_data.db"
    monkeypatch.setenv("DATABASE_URL", url)
    yield


@pytest.fixture(autouse=True)
def _ensure_event_loop():
    """Ensure a current asyncio event loop exists for every test.

    Python 3.10+ no longer auto-creates an event loop on get_event_loop().
    asyncio.run() (used in test_ws_hub) closes and clears the loop after each
    call, which breaks any subsequent test that calls asyncio.get_event_loop()
    directly (e.g. the _run helper in test_master_replay).  This fixture
    creates a fresh loop and sets it as the current loop before each test,
    then closes it after.
    """
    loop = asyncio.new_event_loop()
    asyncio.set_event_loop(loop)
    yield
    loop.close()
    asyncio.set_event_loop(None)
